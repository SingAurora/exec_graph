-- 将平台默认智能合约收敛为唯一的“重点行动指南”。
-- 旧模板只做软删除，历史项目和规则快照仍然可以继续追溯。

UPDATE smart_contracts
SET name = '重点行动指南',
    version = '1.2.0',
    description = '从一件事情中找出最重要的 1～3 个关注点，帮助你认真推进并根据反馈调整。',
    body = '## 这份规则做什么

帮助你把当前要做的事情收束成一个明确行动，并找出决定行动质量的少数关键点。
复杂目标也应拆成多个这样的简单行动，每次只推进眼前最重要的一步。

## 行动关注点

- 先说明这次行动要解决什么问题，或要产出什么结果
- 最多保留 1～3 个关键关注点，不追求列出所有细节
- 关键关注点优先覆盖核心结果、最大风险或最重要的动作
- 记录实际做了什么、哪里和预想不同，以及下一步要怎么调整

## 以点到面

关键关注点是帮助用户集中注意力的观察窗口，不是完整验收清单。
优先从以下三个方向中选择最有价值的点：

- 方向：这次行动最终要改变或产出什么
- 质量：哪一个动作最影响结果是否做到位
- 反馈：做完后需要观察什么，才能决定下一步

默认最多提出三个关注点。简单行动可以只有一个关注点，复杂目标也应先收束为当前一步。

## AI 辅助原则

AI 只能分析用户提供的目标、行动记录和材料，不能知道现实中是否真的发生，也不能替用户证明最终效果。
关键关注点用于帮助用户集中注意力，不是 AI 判断完成与否的硬性门槛。
AI 应优先帮助用户明确重点、识别一个最重要的偏差，并给出一个可执行的下一步。
不要为了补齐形式而追问次要细节，不要求截图、链接或逐条证明，除非用户主动提出或事情本身存在明显风险。
不要把用户的计划改写成已经完成，也不要把记录不完整描述为行动失败。

## 行动记录

完成后只需记录：这次实际做了什么、哪里没有按预想发生、下一步是否需要调整。
用户可以记录完成、部分完成、跳过或暂时无法判断，这些都属于有效的现实反馈。',
    deleted_at = NULL,
    deleted_by = NULL
WHERE uuid = 'smart-contract-quick-action' AND source = 'official';

UPDATE smart_contracts
SET deleted_at = COALESCE(deleted_at, NOW()),
    deleted_by = NULL
WHERE uuid IN ('smart-contract-general', 'smart-contract-daily-routine')
  AND source = 'official';
